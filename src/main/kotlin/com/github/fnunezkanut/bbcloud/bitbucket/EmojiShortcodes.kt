    /** Returns the emoji for [shortcode] (without the surrounding colons), or null when the table does not know it. */
    fun emojiFor(shortcode: String): String? {
        return EMOJI_BY_SHORTCODE[shortcode.lowercase()]
    }

    private fun MutableMap<String, String>.alias(emoji: String, vararg shortcodes: String) {
        shortcodes.forEach { shortcode -> put(shortcode, emoji) }
    }
